LIBRARY ieee;
USE ieee.std_logic_1164.all;

ENTITY i2s_rx_pair IS
  GENERIC(
    d_width       : INTEGER := 24;  -- number of valid audio data bits
    sclk_ws_ratio : INTEGER := 64   -- number of BCLK periods per stereo frame
  );
  PORT(
    reset_n      : IN  STD_LOGIC;   -- asynchronous active-low reset
    mclk         : IN  STD_LOGIC;   -- internal FPGA clock, 25.6 MHz

    ws           : IN  STD_LOGIC;   -- word select / LRCLK: '0' = left, '1' = right
    sclk_rise    : IN  STD_LOGIC;   -- one-mclk-cycle pulse on BCLK rising edge
    bit_index    : IN  INTEGER RANGE 0 TO sclk_ws_ratio-1;
    sample_valid : IN  STD_LOGIC;   -- pulse when full left+right frame is complete

    sd_rx        : IN  STD_LOGIC;   -- shared DOUT line from two I2S microphones

    l_data_rx    : OUT STD_LOGIC_VECTOR(d_width-1 DOWNTO 0);
    r_data_rx    : OUT STD_LOGIC_VECTOR(d_width-1 DOWNTO 0)
  );
END ENTITY;


ARCHITECTURE rtl OF i2s_rx_pair IS

  -- One stereo frame has two slots: left and right.
  -- Example with sclk_ws_ratio = 64:
  --   left slot  = bit_index 0..31
  --   right slot = bit_index 32..63
  CONSTANT slot_width : INTEGER := sclk_ws_ratio / 2;

  -- First valid I2S data bit is delayed by one BCLK after WS changes.
  -- Therefore, in each slot:
  --   local bit 0 = delay bit / unused
  --   local bit 1..d_width = valid audio payload
  CONSTANT left_first_bit  : INTEGER := 1;
  CONSTANT left_last_bit   : INTEGER := d_width;

  CONSTANT right_first_bit : INTEGER := slot_width + 1;
  CONSTANT right_last_bit  : INTEGER := slot_width + d_width;

  -- Internal shift registers.
  -- Data is shifted in MSB first.
  SIGNAL l_shift : STD_LOGIC_VECTOR(d_width-1 DOWNTO 0) := (OTHERS => '0');
  SIGNAL r_shift : STD_LOGIC_VECTOR(d_width-1 DOWNTO 0) := (OTHERS => '0');
  

BEGIN

  PROCESS(mclk, reset_n)
  BEGIN

    IF reset_n = '0' THEN

      -- Clear internal shift registers
      l_shift <= (OTHERS => '0');
      r_shift <= (OTHERS => '0');

      -- Clear output sample registers
      l_data_rx <= (OTHERS => '0');
      r_data_rx <= (OTHERS => '0');

    ELSIF rising_edge(mclk) THEN

      ------------------------------------------------------------------------
      -- Receive serial data on BCLK rising edge.
      --
      -- We do not use rising_edge(sclk) here.
      -- Instead, the central timing block generates sclk_rise as a clean
      -- one-mclk-cycle enable pulse. This keeps the receiver fully synchronous
      -- to mclk.
      ------------------------------------------------------------------------
      IF sclk_rise = '1' THEN

        ----------------------------------------------------------------------
        -- LEFT CHANNEL
        --
        -- In standard I2S, WS changes one BCLK before the MSB.
        --
        -- For a 32-bit left slot:
        --   bit_index = 0      : I2S delay bit
        --   bit_index = 1..24  : valid 24-bit audio data
        --   bit_index = 25..31 : padding / ignored
        ----------------------------------------------------------------------
        IF ws = '0' THEN

          IF bit_index >= left_first_bit AND bit_index <= left_last_bit THEN
            l_shift <= l_shift(d_width-2 DOWNTO 0) & sd_rx;
          END IF;


        ----------------------------------------------------------------------
        -- RIGHT CHANNEL
        --
        -- For a 32-bit right slot:
        --   bit_index = 32     : I2S delay bit
        --   bit_index = 33..56 : valid 24-bit audio data
        --   bit_index = 57..63 : padding / ignored
        ----------------------------------------------------------------------
        ELSE

          IF bit_index >= right_first_bit AND bit_index <= right_last_bit THEN
            r_shift <= r_shift(d_width-2 DOWNTO 0) & sd_rx;
          END IF;

        END IF;
      END IF;


      ------------------------------------------------------------------------
      -- Copy completed shift registers to the output registers.
      --
      -- sample_valid is generated by the central timing block once per full
      -- stereo frame, after both the left and right slot have been received.
      --
      -- At this moment:
      --   l_shift contains the completed left microphone sample
      --   r_shift contains the completed right microphone sample
      --
      -- The outputs remain stable until the next sample_valid pulse.
      ------------------------------------------------------------------------
      IF sample_valid = '1' THEN
        l_data_rx <= l_shift;
        r_data_rx <= r_shift;
      END IF;

    END IF;
  END PROCESS;

END ARCHITECTURE;