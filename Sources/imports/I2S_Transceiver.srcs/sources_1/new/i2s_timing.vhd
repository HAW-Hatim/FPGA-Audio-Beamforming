LIBRARY ieee;
USE ieee.std_logic_1164.all;
 
ENTITY i2s_timing IS
  GENERIC(
    -- Number of mclk periods per complete sclk/BCLK period
    --   mclk = 25.6 MHz
    --   desired sclk = 3.2 MHz
    --   mclk_sclk_ratio = 25.6 MHz / 3.2 MHz = 8
    --   This value must be even, because the code creates sclk by toggling
    --   it after half a period.
    mclk_sclk_ratio : INTEGER := 8;   -- 25.6 MHz / 3.2 MHz = 8
    sclk_ws_ratio   : INTEGER := 64   -- 64 BCLK cycles per stereo frame
  );
  PORT(
    reset_n      : IN  STD_LOGIC;
    mclk         : IN  STD_LOGIC;     -- Master clock generated by clocking wizard
 
    sclk         : OUT STD_LOGIC;     -- BCLK
    ws           : OUT STD_LOGIC;     -- LRCL: '0' = left, '1' = right
 
    sclk_rise    : OUT STD_LOGIC;     -- one mclk pulse at sclk rising edge, for receiver module
    sclk_fall    : OUT STD_LOGIC;     -- one mclk pulse at sclk falling edge, for transmitter module
    sclk_fall_tx : OUT STD_LOGIC;     -- combinatonal early falling-edge enable for TX
 
    -- Current bit position inside the stereo I2S frame
    -- With sclk_ws_ratio = 64:
    --   bit_index = 0  .. 31  -> left slot
    --   bit_index = 32 .. 63  -> right slot
    -- For 24-bit data in 32-bit slots:
    --   left valid bits  = 1  .. 24
    --   right valid bits = 33 .. 56
    bit_index    : OUT INTEGER RANGE 0 TO sclk_ws_ratio-1;
    -- One-mclk-cycle pulse after a complete stereo frame
    -- left sample is complete
    -- right sample is complete
    -- The beamformer/ringbuffer can use this signal to store one new
    -- synchronous sample set
    sample_valid : OUT STD_LOGIC      -- one mclk pulse after right channel complete, complete stereo sample
  );
END ENTITY;
 
ARCHITECTURE rtl OF i2s_timing IS
  SIGNAL sclk_int      : STD_LOGIC := '0';
  SIGNAL ws_int        : STD_LOGIC := '0';
 
  SIGNAL sclk_cnt      : INTEGER RANGE 0 TO mclk_sclk_ratio/2-1 := 0; -- 0,1,2,3 -> then sclk toggles
  SIGNAL bit_cnt       : INTEGER RANGE 0 TO sclk_ws_ratio-1 := 0;     -- 0 to 63; increments once per complete sclk/BCLK period
 
  SIGNAL sclk_rise_int : STD_LOGIC := '0';
  SIGNAL sclk_fall_int : STD_LOGIC := '0';
BEGIN
 
  PROCESS(mclk, reset_n)
  BEGIN
    --------------------------------------------------------------------------
    -- Asynchronous reset
    --------------------------------------------------------------------------
    IF reset_n = '0' THEN                   -- after reset left channel first
      sclk_int      <= '0';
      ws_int        <= '0';
      sclk_cnt      <= 0;
      bit_cnt       <= 0;
      sclk_rise_int <= '0';
      sclk_fall_int <= '0';
      sample_valid  <= '0';
 
    --------------------------------------------------------------------------
    -- Normal operation, synchronous to mclk
    --------------------------------------------------------------------------
    ELSIF rising_edge(mclk) THEN
      sclk_rise_int <= '0';
      sclk_fall_int <= '0';
      sample_valid  <= '0';
 
      ------------------------------------------------------------------------
      -- mclk to sclk divider
      --
      -- This counter waits for half of one BCLK period
      -- Then it toggles sclk_int.
      ------------------------------------------------------------------------
      IF sclk_cnt < (mclk_sclk_ratio / 2 - 1) THEN
        sclk_cnt <= sclk_cnt + 1;
      ELSE
        sclk_cnt <= 0;
 
        ----------------------------------------------------------------------
        -- Generate rising edge of sclk
        ----------------------------------------------------------------------
        IF sclk_int = '0' THEN
          -- sclk changes 0 -> 1
          sclk_int      <= '1';
          sclk_rise_int <= '1';
        ----------------------------------------------------------------------
        -- Generate falling edge of sclk
        ----------------------------------------------------------------------  
        ELSE
          -- sclk changes 1 -> 0
          sclk_int      <= '0';
          sclk_fall_int <= '1';
          --------------------------------------------------------------------
          -- Count complete BCLK periods on falling edge
          --------------------------------------------------------------------
          IF bit_cnt = sclk_ws_ratio - 1 THEN
            -- End of stereo frame
            -- With sclk_ws_ratio = 64 this happens at bit_cnt = 63
            -- next frame starts with left channel
            bit_cnt <= 0;
            ws_int  <= '0';
 
            -- End of full stereo frame
            -- Left and right samples are now complete
            sample_valid <= '1';
          ELSE
            -- Still inside current frame
            -- Move to next BCLK bit position
            bit_cnt <= bit_cnt + 1;
 
            -- First half of frame: left channel
            -- Second half of frame: right channel
            IF bit_cnt = (sclk_ws_ratio / 2 - 1) THEN
              ws_int <= '1';
            END IF;
          END IF;
        END IF;
      END IF;
    END IF;
  END PROCESS;
 
  sclk      <= sclk_int;
  ws        <= ws_int;
  sclk_rise <= sclk_rise_int;
  sclk_fall <= sclk_fall_int;
  bit_index <= bit_cnt;
  -- Combinational early falling-edge enable for TX.
  -- This is high during the mclk edge where sclk will change from '1' to '0'.
  sclk_fall_tx <= '1' WHEN
    (sclk_int = '1' AND sclk_cnt = (mclk_sclk_ratio / 2 - 1))
  ELSE '0';
 
END ARCHITECTURE;