LIBRARY ieee;
USE ieee.std_logic_1164.all;

ENTITY i2s_top_5mic IS
PORT(
    --------------------------------------------------------------------------
    -- Basys3 system signals
    --------------------------------------------------------------------------
   
    -- global active-low reset
    reset_n  : IN STD_LOGIC;

    --------------------------------------------------------------------------
    -- I2S microphone inputs
    --------------------------------------------------------------------------
    -- Shared DOUT line:
    -- Mic1 (left) + Mic2 (right)
    mic_dout_12 : IN STD_LOGIC;

    -- Shared DOUT line:
    -- Mic3 (left) + Mic4 (right)
    mic_dout_34 : IN STD_LOGIC;

    -- Dedicated DOUT line:
    -- Mic5 only
    mic_dout_5 : IN STD_LOGIC;

    --------------------------------------------------------------------------
    -- I2S outputs to microphones
    --------------------------------------------------------------------------
    -- BCLK → all microphones
    mic_bclk : OUT STD_LOGIC;

    -- LRCL → all microphones
    mic_lrcl : OUT STD_LOGIC;

    --------------------------------------------------------------------------
    -- I2S transmitter output
    --------------------------------------------------------------------------
    i2s_sd_tx : OUT STD_LOGIC;
    
    
    -- Clock 25.6MHz Clocking wizard
    mclk_25m6    : in STD_LOGIC;
    
    pll_locked   : in STD_LOGIC;
    
    
    --------------------------------------------------------------------------
    -- debug / processing outputs
    --------------------------------------------------------------------------
    sample_valid_o : OUT STD_LOGIC;
    
    sample_valid_tx: IN STD_LOGIC;
    
    mic1_o : OUT STD_LOGIC_VECTOR(23 DOWNTO 0);
    mic2_o : OUT STD_LOGIC_VECTOR(23 DOWNTO 0);
    mic3_o : OUT STD_LOGIC_VECTOR(23 DOWNTO 0);
    mic4_o : OUT STD_LOGIC_VECTOR(23 DOWNTO 0);
    mic5_o : OUT STD_LOGIC_VECTOR(23 DOWNTO 0);
    
    beam_o : IN STD_LOGIC_VECTOR(23 DOWNTO 0)

);
END ENTITY;

ARCHITECTURE rtl OF i2s_top_5mic IS


SIGNAL i2s_reset_n  : STD_LOGIC;

----------------------------------------------------------------------------
-- Signals generated by i2s_timing
----------------------------------------------------------------------------
SIGNAL sclk          : STD_LOGIC;
SIGNAL ws            : STD_LOGIC;

SIGNAL sclk_rise     : STD_LOGIC;
SIGNAL sclk_fall     : STD_LOGIC;

SIGNAL sample_valid  : STD_LOGIC;

SIGNAL bit_index     : INTEGER RANGE 0 TO 63;

 
SIGNAL sclk_fall_tx : STD_LOGIC;
----------------------------------------------------------------------------
-- Received microphone samples
----------------------------------------------------------------------------
SIGNAL mic1_data : STD_LOGIC_VECTOR(23 DOWNTO 0);
SIGNAL mic2_data : STD_LOGIC_VECTOR(23 DOWNTO 0);

SIGNAL mic3_data : STD_LOGIC_VECTOR(23 DOWNTO 0);
SIGNAL mic4_data : STD_LOGIC_VECTOR(23 DOWNTO 0);

SIGNAL mic5_data : STD_LOGIC_VECTOR(23 DOWNTO 0);

----------------------------------------------------------------------------
-- unused right channel for fifth microphone
----------------------------------------------------------------------------
SIGNAL unused_right :
STD_LOGIC_VECTOR(23 DOWNTO 0);

BEGIN

----------------------------------------------------------------------------
-- I2S logic reset
----------------------------------------------------------------------------
-- I2S modules remain in reset until:
-- 1) user reset released
-- 2) MMCM reports stable clock
----------------------------------------------------------------------------
i2s_reset_n <= reset_n AND pll_locked;


----------------------------------------------------------------------------
-- Central I2S timing generator
----------------------------------------------------------------------------
-- Generates:
-- sclk = BCLK
-- ws = LRCLK
-- bit_index
-- sample_valid
--
-- Shared by ALL microphones.
----------------------------------------------------------------------------
u_i2s_timing :
 
ENTITY work.i2s_timing
 
GENERIC MAP(
    mclk_sclk_ratio => 8,
    sclk_ws_ratio => 64
)
 
PORT MAP(
    reset_n => i2s_reset_n,
    mclk => mclk_25m6,
 
    sclk => sclk,
    ws => ws,
 
    sclk_rise => sclk_rise,
    sclk_fall => sclk_fall,
    sclk_fall_tx => sclk_fall_tx,
 
    bit_index => bit_index,
 
    sample_valid => sample_valid
);

----------------------------------------------------------------------------
-- Receiver 0
----------------------------------------------------------------------------
-- Mic1:
-- SEL -> GND
-- left channel
--
-- Mic2:
-- SEL -> 3V3
-- right channel
----------------------------------------------------------------------------
u_rx_pair_0 :

ENTITY work.i2s_rx_pair

GENERIC MAP(
    d_width => 24,
    sclk_ws_ratio => 64
)

PORT MAP(
    reset_n => i2s_reset_n,
    mclk => mclk_25m6,

    ws => ws,
    sclk_rise => sclk_rise,

    bit_index => bit_index,
    sample_valid => sample_valid,

    sd_rx => mic_dout_12,

    l_data_rx => mic1_data,
    r_data_rx => mic2_data
);

----------------------------------------------------------------------------
-- Receiver 1
----------------------------------------------------------------------------
u_rx_pair_1 :

ENTITY work.i2s_rx_pair

GENERIC MAP(
    d_width => 24,
    sclk_ws_ratio => 64
)

PORT MAP(
    reset_n => i2s_reset_n,
    mclk => mclk_25m6,

    ws => ws,
    sclk_rise => sclk_rise,

    bit_index => bit_index,
    sample_valid => sample_valid,

    sd_rx => mic_dout_34,

    l_data_rx => mic3_data,
    r_data_rx => mic4_data
);

----------------------------------------------------------------------------
-- Receiver 2
----------------------------------------------------------------------------
-- Fifth microphone:
--
-- SEL -> GND
--
-- right channel ignored
----------------------------------------------------------------------------

u_rx_pair_2 :
ENTITY work.i2s_rx_pair

GENERIC MAP(
    d_width => 24,
    sclk_ws_ratio => 64
)

PORT MAP(
    reset_n => i2s_reset_n,
    mclk => mclk_25m6,

    ws => ws,
    sclk_rise => sclk_rise,

    bit_index => bit_index,
    sample_valid => sample_valid,

    sd_rx => mic_dout_5,

    l_data_rx => mic5_data,
    r_data_rx => unused_right
);

----------------------------------------------------------------------------
-- Transmitter
----------------------------------------------------------------------------
-- Temporary:
--
-- send Mic1 and Mic2
--
-- Later:
--
-- replace by beamformer output
----------------------------------------------------------------------------
u_tx :
 
ENTITY work.i2s_tx
 
GENERIC MAP(
    d_width => 24,
    sclk_ws_ratio => 64
)
 
PORT MAP(
    reset_n => i2s_reset_n,
    mclk => mclk_25m6,
 
    ws => ws,
    sclk_fall => sclk_fall_tx,
 
    bit_index => bit_index,
    timing_sample_valid => sample_valid,
    beamformer_valid    => sample_valid_tx,
 
    l_data_tx => beam_o,
    r_data_tx => beam_o,
 
    sd_tx => i2s_sd_tx
);


----------------------------------------------------------------------------
-- External microphone clock outputs
----------------------------------------------------------------------------
mic_bclk <= sclk;

mic_lrcl <= ws;

----------------------------------------------------------------------------
-- Debug outputs
----------------------------------------------------------------------------
sample_valid_o <= sample_valid;

mic1_o <= mic1_data;
mic2_o <= mic2_data;
mic3_o <= mic3_data;
mic4_o <= mic4_data;
mic5_o <= mic5_data;

END ARCHITECTURE;