entity Top_Beamformer is
port (
    Angle : in STD_LOGIC_VECTOR ( 7 downto 0 );
    Clk : in STD_LOGIC;
    clk_25m6: out std_logic;
    Reset : in STD_LOGIC;
    Test_Enable : in STD_LOGIC;
    Mic_Select  : in STD_LOGIC_VECTOR(2 downto 0);
    --    Test_Enable = 0  -> normaler Beamformer
    --    Test_Enable = 1  -> Mikrofon-Testmodus
    --    Mic_Select = 000 -> Mic 1
    --    Mic_Select = 001 -> Mic 2
    --    Mic_Select = 010 -> Mic 3
    --    Mic_Select = 011 -> Mic 4
    --    Mic_Select = 100 -> Mic 5
    i2s_sd_tx : out STD_LOGIC;
    mic_bclk : out STD_LOGIC;
    mic_dout_12 : in STD_LOGIC;
    mic_dout_34 : in STD_LOGIC;
    mic_dout_5 : in STD_LOGIC;
    mic_lrcl : out STD_LOGIC;
    das_valid: out std_logic;
    audio_out_DAS: out std_logic_vector(23 downto 0);
    
    Anode_Activate : out STD_LOGIC_VECTOR (3 downto 0); -- Anodensignale
    LED_out : out STD_LOGIC_VECTOR (6 downto 0) -- Kathodenmuster  
    
  );
end Top_Beamformer;

architecture Behavioral of Top_Beamformer is

component delay_and_sum is
  port (
    audio_mic_0 : in STD_LOGIC_VECTOR ( 23 downto 0 );
    audio_mic_1 : in STD_LOGIC_VECTOR ( 23 downto 0 );
    audio_mic_2 : in STD_LOGIC_VECTOR ( 23 downto 0 );
    audio_mic_3 : in STD_LOGIC_VECTOR ( 23 downto 0 );
    audio_mic_4 : in STD_LOGIC_VECTOR ( 23 downto 0 );
    Clk : in STD_LOGIC;
    Reset : in STD_LOGIC;
    valid_in : in STD_LOGIC;
    delay_0 : in STD_LOGIC_VECTOR ( 4 downto 0 );
    delay_1 : in STD_LOGIC_VECTOR ( 4 downto 0 );
    delay_2 : in STD_LOGIC_VECTOR ( 4 downto 0 );
    delay_3 : in STD_LOGIC_VECTOR ( 4 downto 0 );
    delay_4 : in STD_LOGIC_VECTOR ( 4 downto 0 );
    audio_out : out STD_LOGIC_VECTOR ( 23 downto 0 );
    valid_out : out STD_LOGIC
  );
  end component delay_and_sum;
  
component i2s_top_5mic is
  port (
    reset_n : in STD_LOGIC;
    mic_dout_12 : in STD_LOGIC;
    mic_dout_34 : in STD_LOGIC;
    mic_dout_5 : in STD_LOGIC;
    mic_bclk : out STD_LOGIC;
    mic_lrcl : out STD_LOGIC;
    i2s_sd_tx : out STD_LOGIC;
    sample_valid_o : out STD_LOGIC;
    sample_valid_tx : in STD_LOGIC;
    mic1_o : out STD_LOGIC_VECTOR ( 23 downto 0 );
    mic2_o : out STD_LOGIC_VECTOR ( 23 downto 0 );
    mic3_o : out STD_LOGIC_VECTOR ( 23 downto 0 );
    mic4_o : out STD_LOGIC_VECTOR ( 23 downto 0 );
    mic5_o : out STD_LOGIC_VECTOR ( 23 downto 0 );
    beam_o : in STD_LOGIC_VECTOR ( 23 downto 0 );
    mclk_25m6    : in STD_LOGIC;
    pll_locked   : in STD_LOGIC
  );
end component i2s_top_5mic;

component Angle_to_delay is
  port (
    Clk : in STD_LOGIC;
    Angle : in STD_LOGIC_VECTOR ( 7 downto 0 );
    delay_0 : out STD_LOGIC_VECTOR ( 4 downto 0 );
    delay_1 : out STD_LOGIC_VECTOR ( 4 downto 0 );
    delay_2 : out STD_LOGIC_VECTOR ( 4 downto 0 );
    delay_3 : out STD_LOGIC_VECTOR ( 4 downto 0 );
    delay_4 : out STD_LOGIC_VECTOR ( 4 downto 0 );
    Reset_n : in STD_LOGIC;
    Z1 : out INTEGER range 0 to 11; -- linkeste Ziffer (Tausenderstelle)
    Z2 : out INTEGER range 0 to 11; -- Hunderterstelle
    Z3 : out INTEGER range 0 to 11; -- Zehnerstelle
    Z4 : out INTEGER range 0 to 11 -- Einerstelle
  );
end component Angle_to_delay;
  
component seven_segment_display is
    Port (
        Clk : in STD_LOGIC;  -- 100 MHz Takt des Basys 3 Boards
        reset : in STD_LOGIC; -- Reset-Signal
        -- Zifferneingaben (0 bis 9 und -, sowie others)
        Z1 : in INTEGER range 0 to 11; -- linkeste Ziffer (Tausenderstelle)
        Z2 : in INTEGER range 0 to 11; -- Hunderterstelle
        Z3 : in INTEGER range 0 to 11; -- Zehnerstelle
        Z4 : in INTEGER range 0 to 11; -- Einerstelle
        -- Ausgaenge fuer die 7-Segment-Anzeige
        Anode_Activate : out STD_LOGIC_VECTOR (3 downto 0); -- Anodensignale
        LED_out : out STD_LOGIC_VECTOR (6 downto 0) -- Kathodenmuster
    );
end component seven_segment_display;
  
  
  ----------------------------------------------------------------------------
-- Clock Wizard component
----------------------------------------------------------------------------
-- Generated by Vivado:
-- input:
--      100 MHz
-- output:
--      25.6 MHz
-- locked:
--      becomes '1' once MMCM output is stable
----------------------------------------------------------------------------
COMPONENT clk_wiz_I2S
PORT(
     clk_out1 : OUT STD_LOGIC;
     reset    : IN STD_LOGIC;
     locked   : OUT STD_LOGIC;
     clk_in1  : IN STD_LOGIC
);
END COMPONENT;

----------------------------------------------------------------------------
-- 7-Segment signals
----------------------------------------------------------------------------
-- Zifferneingaben (0 bis 11)
signal z1 : INTEGER range 0 to 11; -- linkeste Ziffer (Tausenderstelle)
signal z2 : INTEGER range 0 to 11; -- Hunderterstelle
signal z3 : INTEGER range 0 to 11; -- Zehnerstelle
signal z4 : INTEGER range 0 to 11; -- Einerstelle

----------------------------------------------------------------------------
-- Clock signals
----------------------------------------------------------------------------
SIGNAL pll_locked    : STD_LOGIC;
SIGNAL mclk_25m6    : STD_LOGIC;
SIGNAL clk_reset    : STD_LOGIC;
  
signal delay_0 : STD_LOGIC_VECTOR ( 4 downto 0 );
signal delay_1 : STD_LOGIC_VECTOR ( 4 downto 0 );
signal delay_2 : STD_LOGIC_VECTOR ( 4 downto 0 );
signal delay_3 : STD_LOGIC_VECTOR ( 4 downto 0 );
signal delay_4 : STD_LOGIC_VECTOR ( 4 downto 0 );
signal beamformer_o : STD_LOGIC_VECTOR ( 23 downto 0 );
signal beamformer_valid : STD_LOGIC;
signal mic1_o : STD_LOGIC_VECTOR ( 23 downto 0 );
signal mic2_o : STD_LOGIC_VECTOR ( 23 downto 0 );
signal mic3_o : STD_LOGIC_VECTOR ( 23 downto 0 );
signal mic4_o : STD_LOGIC_VECTOR ( 23 downto 0 );
signal mic5_o : STD_LOGIC_VECTOR ( 23 downto 0 );
signal sample_valid : STD_LOGIC;

----------------------------------------------------------------------------
-- Test mode / audio mux signals
----------------------------------------------------------------------------
signal tx_audio : STD_LOGIC_VECTOR(23 downto 0);
signal tx_valid : STD_LOGIC;
 
signal test_enable_meta : STD_LOGIC := '0';
signal test_enable_sync : STD_LOGIC := '0';
 
signal mic_select_meta : STD_LOGIC_VECTOR(2 downto 0) := (others => '0');
signal mic_select_sync : STD_LOGIC_VECTOR(2 downto 0) := (others => '0');
 
signal test_enable_frame : STD_LOGIC := '0';
signal mic_select_frame : STD_LOGIC_VECTOR(2 downto 0) := (others => '0'); 
   
   

begin

----------------------------------------------------------------------------
-- Synchronize external switches to 25.6 MHz I2S clock domain
----------------------------------------------------------------------------
process(mclk_25m6, Reset)
begin
    if Reset = '0' then
        test_enable_meta <= '0';
        test_enable_sync <= '0';
 
        mic_select_meta <= (others => '0');
        mic_select_sync <= (others => '0');
 
    elsif rising_edge(mclk_25m6) then
        test_enable_meta <= Test_Enable;
        test_enable_sync <= test_enable_meta;
 
        mic_select_meta <= Mic_Select;
        mic_select_sync <= mic_select_meta;
    end if;
end process;
 
----------------------------------------------------------------------------
-- Latch test selection only once per audio frame
----------------------------------------------------------------------------
process(mclk_25m6, Reset)
begin
    if Reset = '0' then
        test_enable_frame <= '0';
        mic_select_frame <= (others => '0');
 
    elsif rising_edge(mclk_25m6) then
        if sample_valid = '1' then
            test_enable_frame <= test_enable_sync;
            mic_select_frame <= mic_select_sync;
        end if;
    end if;
end process;
 
----------------------------------------------------------------------------
-- Audio output selection
----------------------------------------------------------------------------
process(test_enable_frame, mic_select_frame,
        beamformer_o,
        mic1_o,
        mic2_o,
        mic3_o,
        mic4_o,
        mic5_o,
        beamformer_valid,
        sample_valid)
begin
    if test_enable_frame = '0' then
        -- Normal operation: beamformer output
        tx_audio <= beamformer_o;
        tx_valid <= beamformer_valid;
 
    else
        -- Test mode: direct microphone output
        tx_valid <= sample_valid;
     
        case mic_select_frame is
          when "000" =>
            tx_audio <= mic1_o;
          when "001" =>
            tx_audio <= mic2_o;
          when "010" =>
            tx_audio <= mic3_o;
          when "011" =>
            tx_audio <= mic4_o;
          when "100" =>
            tx_audio <= mic5_o;
          when others =>
            tx_audio <= (others => '0');
        end case;
    end if;
end process;

----------------------------------------------------------------------------
-- Clock wizard reset
----------------------------------------------------------------------------
-- Clock Wizard reset is ACTIVE HIGH
----------------------------------------------------------------------------
clk_reset <= NOT Reset;
----------------------------------------------------------------------------
-- Clock Wizard
----------------------------------------------------------------------------
-- Creates:
--      100 MHz -> 25.6 MHz
----------------------------------------------------------------------------
u_clk_wiz : component clk_wiz_I2S
PORT MAP(
    clk_in1  => Clk,
    reset    => clk_reset,

    clk_out1 => mclk_25m6,
    locked   => pll_locked
);

Angle_to_delay_0: component Angle_to_delay
     port map (
      Angle(7 downto 0) => Angle(7 downto 0),
      Clk => mclk_25m6,
      Reset_n => Reset,
      delay_0(4 downto 0) => delay_0(4 downto 0),
      delay_1(4 downto 0) => delay_1(4 downto 0),
      delay_2(4 downto 0) => delay_2(4 downto 0),
      delay_3(4 downto 0) => delay_3(4 downto 0),
      delay_4(4 downto 0) => delay_4(4 downto 0),
      Z1 => Z1,
      Z2 => Z2,
      Z3 => Z3,
      Z4 => Z4
    );
    
delay_and_sum_0: component delay_and_sum
     port map (
      Clk => mclk_25m6,
      Reset => Reset,
      audio_mic_0(23 downto 0) => mic1_o(23 downto 0),
      audio_mic_1(23 downto 0) => mic2_o(23 downto 0),
      audio_mic_2(23 downto 0) => mic3_o(23 downto 0),
      audio_mic_3(23 downto 0) => mic4_o(23 downto 0),
      audio_mic_4(23 downto 0) => mic5_o(23 downto 0),
      audio_out(23 downto 0) => beamformer_o(23 downto 0),
      delay_0(4 downto 0) => delay_0(4 downto 0),
      delay_1(4 downto 0) => delay_1(4 downto 0),
      delay_2(4 downto 0) => delay_2(4 downto 0),
      delay_3(4 downto 0) => delay_3(4 downto 0),
      delay_4(4 downto 0) => delay_4(4 downto 0),
      valid_in => sample_valid,
      valid_out => beamformer_valid
    );
    
i2s_top_5mic_0: component i2s_top_5mic
     port map (
      beam_o(23 downto 0) => tx_audio(23 downto 0),
      --beam_o(23 downto 0) => beamformer_o(23 downto 0),
      i2s_sd_tx => i2s_sd_tx,
      mic1_o(23 downto 0) => mic1_o(23 downto 0),
      mic2_o(23 downto 0) => mic2_o(23 downto 0),
      mic3_o(23 downto 0) => mic3_o(23 downto 0),
      mic4_o(23 downto 0) => mic4_o(23 downto 0),
      mic5_o(23 downto 0) => mic5_o(23 downto 0),
      mic_bclk => mic_bclk,
      mic_dout_12 => mic_dout_12,
      mic_dout_34 => mic_dout_34,
      mic_dout_5 => mic_dout_5,
      mic_lrcl => mic_lrcl,
      reset_n => Reset,
      sample_valid_o => sample_valid,
      sample_valid_tx => tx_valid,
      --sample_valid_tx => beamformer_valid,
      pll_locked   => pll_locked,
      mclk_25m6 => mclk_25m6
    );
    
seven_segment_display_0: component seven_segment_display
    Port map(
        Clk => mclk_25m6,  -- 100 MHz Takt des Basys 3 Boards
        reset => Reset, -- Reset-Signal
        -- Zifferneingaben (0 bis 9 und -, sowie others)
        Z1 => Z1,-- linkeste Ziffer (Tausenderstelle)
        Z2 => Z2,-- Hunderterstelle
        Z3 => Z3,-- Zehnerstelle
        Z4 => Z4,-- Einerstelle
        -- Ausgaenge fuer die 7-Segment-Anzeige
        Anode_Activate => Anode_Activate, -- Anodensignale
        LED_out => LED_out -- Kathodenmuster
    );

    
-- Input for FFT stages
das_valid <= beamformer_valid;
audio_out_DAS <= beamformer_o;
clk_25m6 <= mclk_25m6;
  

end Behavioral;
